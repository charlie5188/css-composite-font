#!/usr/bin/env python3
"""Build pinned Unicode repertoires used by exact inspection and loose browsing.

GB 2312 uses CPython's gb2312 mapping of the assigned double-byte graphic set.
JIS and Big5 use Unicode's v2.0 legacy mappings (2015 headers). Unmapped and
replacement entries and duplicate Unicode values are not counted. No ASCII or
control characters are added beyond the mapped double-byte repertoire.
"""
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://www.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/'
SOURCES = {'tc': ('OTHER/BIG5.TXT', 1, 'd1b60c58a1d327918f1616a620162c60ad2079a229ee42a73488f186e11f3aac'), 'jp': ('JIS/JIS0208.TXT', 2, '1c571870457f19c97720631fa83ee491549a96ba1436da1296786a67d8632e87')}
BASIC = {
    'latin': 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz', 'digit': '0123456789',
    'kana': 'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをんアイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲンー',
    'pinyin': 'āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜü',
    'shared': '“”‘’—…·', 'punct': '「」『』（）、。！？',
    'symbol': '①②③※→℃ＡＢＣ１２３',
    'bopo': ''.join(chr(c) for c in range(0x3105, 0x312a)) + 'ˊˇˋ˙',
}


def build():
    sets, provenance = {}, {}
    gb = set()
    for a in range(0xa1, 0xff):
        for b in range(0xa1, 0xff):
            try:
                gb.add(bytes([a, b]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    sets['sc'] = ''.join(sorted(gb))
    assert len(sets['sc']) == 7445
    assert hashlib.sha256(sets['sc'].encode()).hexdigest() == '63d45232d921b8598e6417605b7970e900e7de72622b8c495d9270c0c81cc9ee'
    provenance['sc'] = {'version': 'GB 2312-80', 'source': 'https://github.com/python/cpython/tree/3.12/Modules/cjkcodecs', 'mapping': 'CPython gb2312; assigned double-byte graphics'}
    for key, (path, column, expected_hash) in SOURCES.items():
        raw = urllib.request.urlopen(BASE + path, timeout=30).read()
        assert hashlib.sha256(raw).hexdigest() == expected_hash, 'Mapping changed; review the pinned version before updating.'
        chars = set()
        for line in raw.decode().splitlines():
            fields = line.split('#')[0].split()
            if len(fields) <= column:
                continue
            code = int(fields[column], 16)
            if code != 0xfffd:
                chars.add(chr(code))
        sets[key] = ''.join(sorted(chars))
        provenance[key] = {'version': 'Big5' if key == 'tc' else 'JIS X 0208:1990', 'source': BASE + path, 'mapping': 'Unicode mapping v2.0 (2015-12-02)', 'sourceSha256': hashlib.sha256(raw).hexdigest()}
    assert len(sets['jp']) == 6879
    assert len(sets['tc']) == 13703
    for key, chars in BASIC.items():
        sets[key] = ''.join(sorted(set(chars)))
    for key, chars in sets.items():
        provenance.setdefault(key, {'version': key, 'mapping': 'Fixed basic set defined in tools/charsetmeta.py'})
        provenance[key]['total'] = len(chars)
        provenance[key]['unicodeSha256'] = hashlib.sha256(chars.encode()).hexdigest()
    data = {key: {**provenance[key], 'chars': chars} for key, chars in sets.items()}
    target = ROOT / 'assets/js/charset-data.js'
    target.write_text('/* Generated by tools/charsetmeta.py; do not hand-edit.\n'
                      '   See assets/LICENSE-Unicode.txt and assets/LICENSE-Python.txt. */\n'
                      'export const CHARSETS = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print({key: len(chars) for key, chars in sets.items()})


if __name__ == '__main__':
    build()
