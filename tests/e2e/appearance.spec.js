const { test, expect } = require('@playwright/test');
const { open, pick, setLang } = require('./helpers');
const settings = async page => { if (!await page.locator('#moreMenu').isVisible()) await page.click('#moreBtn'); };
const theme = async (page, value) => { await settings(page); await page.selectOption('#appearanceTheme', value); };
const colors = async page => {
  if (!await page.locator('#viewBtn').isVisible()) await page.click('#mTabs [data-mv="preview"]');
  if (!await page.locator('#viewPop').isVisible()) await page.click('#viewBtn');
};
const proof = page => page.locator('#proofText');
const config = page => page.evaluate(async () => {
  const core = await import('./assets/js/core.js'), share = await import('./assets/js/share.js'), ex = await import('./assets/js/export.js');
  ex.renderExport(); return { config: core.presetSnap(), history: core.hist.list.length, shared: share.shareSnapshot(), output: ex.lastExport };
});

test('外观：手动浅深色覆盖系统，跟随系统实时更新并在重载后保留', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' }); await open(page);
  await expect(proof(page)).toHaveCSS('color', 'rgb(17, 17, 18)');
  await theme(page, 'dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(proof(page)).toHaveCSS('color', 'rgb(237, 237, 234)');
  await expect(page.locator('#proofBgHex')).toHaveValue('#161617');
  await colors(page); await page.locator('#proofBgHex').focus(); await page.locator('#proofBgHex').press('Tab');
  await expect(page.locator('#appearanceReset')).toBeDisabled();
  await page.reload();
  await expect(proof(page)).toHaveCSS('color', 'rgb(237, 237, 234)');
  await page.emulateMedia({ colorScheme: 'dark' }); await theme(page, 'light');
  await expect(proof(page)).toHaveCSS('color', 'rgb(17, 17, 18)');
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'light');
  await theme(page, 'system');
  await expect(proof(page)).toHaveCSS('color', 'rgb(237, 237, 234)');
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(proof(page)).toHaveCSS('color', 'rgb(17, 17, 18)');
  await expect(page.locator('#proofBgHex')).toHaveValue('#FFFFFF');
  await page.reload(); await settings(page);
  await expect(page.locator('#appearanceTheme')).toHaveValue('system');
  await expect(page.locator('#moreBtn')).toHaveAttribute('aria-expanded', 'true');
  await page.keyboard.press('Escape');
  await expect(page.locator('#moreMenu')).toBeHidden();
});

test('校样颜色：即时预览、有效色码与恢复默认；预设、撤销、分享及导出保持独立', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' }); await open(page);
  await expect.poll(() => page.evaluate(async () => (await import('./assets/js/core.js')).hist.list.length)).toBeGreaterThan(0);
  const before = await config(page);
  await colors(page);
  await page.fill('#proofBgHex', '#F5F0E8'); await page.locator('#proofBgHex').press('Enter');
  await page.locator('[data-appearance-color="text"]').fill('#234567');
  await expect(proof(page)).toHaveCSS('color', 'rgb(35, 69, 103)');
  await expect(page.locator('#sheet')).toHaveCSS('background-color', 'rgb(245, 240, 232)');
  await expect(page.locator('#spec')).toHaveCSS('background-color', 'rgb(245, 240, 232)');
  await expect(page.locator('.pane-bar')).toHaveCSS('background-color', 'rgb(255, 255, 255)');
  expect(await config(page)).toEqual(before);
  await page.fill('#proofInkHex', '#abc'); await page.locator('#proofInkHex').press('Enter');
  await expect(page.locator('#proofInkHex')).toHaveValue('#AABBCC');
  await page.fill('#proofInkHex', 'invalid'); await page.locator('#proofInkHex').press('Tab');
  await expect(page.locator('#proofInkHex')).toHaveValue('#AABBCC');
  await page.keyboard.press('Escape');
  await pick(page, 'sans-sc');
  await expect(proof(page)).toHaveCSS('color', 'rgb(170, 187, 204)');
  await page.reload();
  await expect(proof(page)).toHaveCSS('color', 'rgb(170, 187, 204)');
  await page.click('#ltabFonts');
  const size = page.locator('#classRows [data-id="latin"] [data-field="size"]');
  await size.fill('119'); await size.press('Tab');
  await expect(page.locator('#undoBtn')).toBeEnabled(); await page.click('#undoBtn');
  await expect(proof(page)).toHaveCSS('color', 'rgb(170, 187, 204)');
  const link = await page.evaluate(async () => (await import('./assets/js/share.js')).shareLink());
  await page.goto(link);
  await expect(page.locator('#toast')).toContainText('已载入分享配置');
  await expect(proof(page)).toHaveCSS('color', 'rgb(170, 187, 204)');
  await page.click('#ltabPresets'); await page.click('#savePresetBtn'); await page.click('#saveOk');
  const library = await page.evaluate(() => localStorage.getItem('composite-font:presets:v1'));
  expect(library).not.toContain('appearance'); expect(library).not.toContain('#aabbcc');
  await theme(page, 'dark');
  await expect(page.locator('#sheet')).toHaveCSS('background-color', 'rgb(245, 240, 232)');
  await colors(page); await page.click('#appearanceReset');
  await expect(page.locator('#appearanceReset')).toBeDisabled();
  await expect(proof(page)).toHaveCSS('color', 'rgb(237, 237, 234)');
  await expect(page.locator('#spec')).toHaveCSS('background-color', 'rgb(22, 22, 23)');
  await theme(page, 'light');
  await expect(proof(page)).toHaveCSS('color', 'rgb(17, 17, 18)');
});

test('外观：四种语言、键盘和窄屏设置，损坏或不可用的存储不阻断编辑', async ({ page }) => {
  await open(page);
  for (const lang of ['tw', 'ja', 'en', 'zh']) {
    await setLang(page, lang); await settings(page);
    await expect(page.locator('#appearanceTheme option')).toHaveCount(3);
    await expect(page.locator('#moreMenu [data-appearance-hex]')).toHaveCount(0);
    await expect(page.locator('#appearanceTheme')).toHaveAccessibleName(/外觀|外観|Appearance|外观/);
    await colors(page);
    await expect(page.locator('#viewPop [data-appearance-hex]')).toHaveCount(2);
    await expect(page.locator('#proofBgHex')).toHaveValue(/#[\dA-F]{6}/);
    await expect(page.locator('#viewBtn')).toHaveAttribute('aria-expanded', 'true');
    await page.keyboard.press('Escape');
    await expect(page.locator('#viewBtn')).toHaveAttribute('aria-expanded', 'false');
  }
  await page.setViewportSize({ width: 390, height: 600 }); await settings(page);
  const rect = await page.locator('#moreMenu').boundingBox();
  expect(rect.x).toBeGreaterThanOrEqual(8); expect(rect.x + rect.width).toBeLessThanOrEqual(382);
  expect(rect.y + rect.height).toBeLessThanOrEqual(592);
  await colors(page);
  const viewRect = await page.locator('#viewPop').boundingBox();
  expect(viewRect.x).toBeGreaterThanOrEqual(8); expect(viewRect.x + viewRect.width).toBeLessThanOrEqual(382);
  expect(viewRect.y).toBeGreaterThanOrEqual(8); expect(viewRect.y + viewRect.height).toBeLessThanOrEqual(592);
  await page.locator('#appearanceReset').scrollIntoViewIfNeeded();
  await expect(page.locator('#appearanceReset')).toBeVisible();
  await colors(page); await page.locator('#proofBgHex').focus(); await page.locator('#proofBgHex').press('Tab');
  await expect(page.locator('[data-appearance-color="text"]')).toBeFocused();
  await page.evaluate(() => localStorage.setItem('composite-font:appearance:v1', JSON.stringify({ theme: 'bad', background: 'red;display:none', text: '#112233' })));
  await page.reload(); await settings(page);
  await expect(page.locator('#appearanceTheme')).toHaveValue('system');
  await expect(proof(page)).toHaveCSS('color', 'rgb(17, 34, 51)');
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Denied', 'SecurityError'); }; });
  await page.selectOption('#appearanceTheme', 'dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await colors(page); await page.click('#appearanceReset');
  await expect(proof(page)).toHaveCSS('color', 'rgb(237, 237, 234)');
});
