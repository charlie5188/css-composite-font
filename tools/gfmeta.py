#!/usr/bin/env python3
"""Regenerate assets/js/gfmeta.js: Google Fonts metadata (variable axes, italics, axis names, and CJK font styles).

fonts.google.com/metadata/fonts blocks direct browser access, so a copy is bundled. Usage:
    python3 tools/gfmeta.py            # Fetch current metadata and write assets/js/gfmeta.js
    python3 tools/gfmeta.py meta.json  # Use a previously downloaded file
"""
import json, sys, urllib.request, datetime, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets/js/gfmeta.js'
CJK = ('chinese-simplified', 'chinese-traditional', 'chinese-hongkong', 'japanese', 'korean')
CJ = CJK[:-1]


def cj_families(metadata):
    """Use Google's language subsets, rather than a second hand-maintained picker list."""
    return sorted(f['family'] for f in metadata['familyMetadataList'] if any(subset in f.get('subsets', []) for subset in CJ))


def load(src=None):
    raw = pathlib.Path(src).read_text('utf-8') if src else urllib.request.urlopen('https://fonts.google.com/metadata/fonts').read().decode('utf-8')
    if raw.startswith(")]}'"):
        raw = raw[4:]
    return json.loads(raw)


def num(x):
    return str(int(x)) if float(x).is_integer() else repr(float(x))


def style_of(f):
    """CJK style: display, handwriting and monospace families are classified as other; otherwise check stroke, then category."""
    if f.get('classifications'):
        return 'other'
    s = f.get('stroke') or f.get('category')
    return {'Serif': 'serif', 'Sans Serif': 'sans'}.get(s, 'other')


def build(d):
    fams = sorted(d['familyMetadataList'], key=lambda f: f['family'])
    axes = {f['family']: ','.join(f"{a['tag']} {num(a['min'])} {num(a['max'])} {num(a['defaultValue'])}" for a in sorted(f['axes'], key=lambda a: a['tag']))
            for f in fams if f.get('axes')}
    italic = [f['family'] for f in fams if any(k.endswith('i') for k in f.get('fonts', {}))]
    used = {a['tag'] for f in fams for a in f.get('axes', [])}      # Include only axes used by at least one family.
    names = {a['tag']: a['displayName'] for a in sorted(d['axisRegistry'], key=lambda a: a['tag']) if a['tag'] in used}
    style = {'serif': [], 'sans': [], 'other': []}
    for f in fams:
        if any(s in f.get('subsets', []) for s in CJK):
            style[style_of(f)].append(f['family'])
    style = {k: ','.join(v) for k, v in style.items()}
    # Families without wght: available upright weights encoded as single digits representing multiples of 100, e.g. "47" = 400 and 700.
    weights = {f['family']: ''.join(sorted({str(int(k) // 100) for k in f.get('fonts', {}) if k.isdigit() and int(k) % 100 == 0}))
               for f in fams if not any(a['tag'] == 'wght' for a in f.get('axes', []))}
    weights = {k: v for k, v in weights.items() if v}
    j = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
    month = datetime.date.today().strftime('%Y-%m')
    return (f"/* Google Fonts metadata (retrieved {month} from fonts.google.com/metadata/fonts; bundled because the endpoint blocks direct browser access). Generated by tools/gfmeta.py; do not edit manually.\n"
            "   GF_AXES: variable axes as 'tag minimum maximum default'; GF_ITALIC: families with italics; AXIS_NAMES: English axis names. Unknown families still probe wght online.\n"
            "   GF_STYLE: comma-separated CJK families by style (serif = Song/Ming, sans = Hei/Gothic, other = display, handwriting or monospace).\n"
            "   GF_WEIGHTS: upright weights for families without wght, encoded as single digits representing weight / 100.\n"
            "   GF_CJ: every family tagged for Chinese or Japanese in this metadata snapshot. */\n"
            f"export const GF_CJ = {j(cj_families(d))};\n"
            f"export const GF_AXES = {j(axes)};\n"
            f"export const GF_ITALIC = new Set({j('|'.join(italic))}.split('|'));\n"
            f"export const AXIS_NAMES = {j(names)};\n"
            f"export const GF_STYLE = {j(style)};\n"
            f"export const GF_WEIGHTS = {j(weights)};\n")


if __name__ == '__main__':
    OUT.write_text(build(load(sys.argv[1] if len(sys.argv) > 1 else None)), 'utf-8')
    print('wrote', OUT.relative_to(ROOT))
